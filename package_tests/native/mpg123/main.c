static short decoded[RATE];

/* Decode the fixture with one decoder core; return the number of samples, or -1 on an error. */
static long decode_with(const char *decoder) {
    int error = MPG123_OK;
    mpg123_handle *handle = mpg123_new(decoder, &error);
    if (handle == NULL) {
        fprintf(stderr, "mpg123_new(%s): %s\n", decoder, mpg123_plain_strerror(error));
        return -1;
    }
    mpg123_format_none(handle);
    mpg123_format(handle, RATE, MPG123_MONO, MPG123_ENC_SIGNED_16);
    if (mpg123_open_feed(handle) != MPG123_OK) {
        fprintf(stderr, "%s: mpg123_open_feed: %s\n", decoder, mpg123_strerror(handle));
        mpg123_delete(handle);
        return -1;
    }
    size_t total = 0;
    size_t done = 0;
    int status = mpg123_decode(handle, tone_mp3, sizeof tone_mp3, (unsigned char *) decoded, sizeof decoded, &done);
    total += done;
    while (status == MPG123_OK || status == MPG123_NEW_FORMAT) {
        status = mpg123_decode(handle, NULL, 0, (unsigned char *) decoded + total, sizeof decoded - total, &done);
        total += done;
        if (done == 0 && status != MPG123_NEW_FORMAT) {
            break;
        }
    }
    if (status != MPG123_NEED_MORE && status != MPG123_OK && status != MPG123_DONE) {
        fprintf(stderr, "%s: mpg123_decode: %s\n", decoder, mpg123_strerror(handle));
        mpg123_delete(handle);
        return -1;
    }
    mpg123_delete(handle);
    return (long) (total / sizeof(short));
}

int main(void) {
    unsigned int patch = 0;
    const unsigned int api = mpg123_libversion(&patch);
    if (api != MPG123_API_VERSION) {
        fprintf(stderr, "header API %d but the library reports API %u\n", MPG123_API_VERSION, api);
        return 1;
    }

    unsigned int major = 0;
    unsigned int minor = 0;
    unsigned int micro = 0;
    const char *distribution = mpg123_distversion(&major, &minor, &micro);

    const char **decoders = mpg123_decoders();
    if (decoders == NULL || decoders[0] == NULL) {
        fprintf(stderr, "no decoder cores are compiled in\n");
        return 1;
    }
    printf("decoder cores:");
    for (const char **decoder = decoders; *decoder != NULL; ++decoder) {
        printf(" %s", *decoder);
    }
    printf("\n");

    int error = MPG123_OK;
    mpg123_handle *handle = mpg123_new(NULL, &error);
    if (handle == NULL) {
        fprintf(stderr, "mpg123_new: %s\n", mpg123_plain_strerror(error));
        return 1;
    }
    printf("mpg123 %s (API %u): opened a handle on decoder %s\n", distribution != NULL ? distribution : "?", api,
           mpg123_current_decoder(handle));
    mpg123_delete(handle);

    /* Decode the embedded tone with every core this CPU supports and check the samples. */
    const char **supported = mpg123_supported_decoders();
    int checked = 0;
    int failures = 0;
    for (const char **decoder = supported; decoder != NULL && *decoder != NULL; ++decoder) {
        const long samples = decode_with(*decoder);
        if (samples < WINDOW_START + WINDOW_SAMPLES) {
            fprintf(stderr, "%s: decoded %ld samples, need at least %d\n", *decoder, samples,
                    WINDOW_START + WINDOW_SAMPLES);
            ++failures;
            continue;
        }
        double in_phase = 0.0;
        double quadrature = 0.0;
        double energy = 0.0;
        for (int index = 0; index < WINDOW_SAMPLES; ++index) {
            const double value = (double) decoded[WINDOW_START + index] / 32768.0;
            const double angle = 2.0 * M_PI * TONE_HZ * (double) index / (double) RATE;
            in_phase += value * cos(angle);
            quadrature += value * sin(angle);
            energy += value * value;
        }
        const double amplitude = 2.0 * sqrt(in_phase * in_phase + quadrature * quadrature) / (double) WINDOW_SAMPLES;
        const double residual_power = energy / (double) WINDOW_SAMPLES - amplitude * amplitude / 2.0;
        const double residual_rms = residual_power > 0.0 ? sqrt(residual_power) : 0.0;
        ++checked;
        if (fabs(amplitude - FIXTURE_AMPLITUDE) > 0.05 || residual_rms > 0.05) {
            fprintf(stderr, "%s: decoded tone amplitude %.4f (expected %.3f), residual RMS %.4f\n", *decoder, amplitude,
                    FIXTURE_AMPLITUDE, residual_rms);
            ++failures;
            continue;
        }
        printf("%s: decoded %ld samples; %.0f Hz tone amplitude %.4f, residual RMS %.4f\n", *decoder, samples, TONE_HZ,
               amplitude, residual_rms);
    }
    if (checked == 0) {
        fprintf(stderr, "no supported decoder core decoded the fixture\n");
        return 1;
    }
    return failures == 0 ? 0 : 1;
}
